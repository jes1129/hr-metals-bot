# 呼叫端如何偵測訊號標記
# =============================================================================

SIGNAL_INSUFFICIENT = "(資料不足)"
SIGNAL_NEEDS_HUMAN = "(需人工判斷)"


def has_signal(reason: str, signal: str) -> bool:
    """判斷模型回覆中是否帶有指定訊號標記。

    用法：
        out = ai.summarize(prompts.verify_system(FIELDS, "供應商分析"), payload,
                           ("ok", "reason"))
        if out and out["ok"] != "true":
            if prompts.has_signal(out["reason"], prompts.SIGNAL_INSUFFICIENT):
                ...  # 資料本身不足，回頭補抓，重試同一提示無用
            else:
                ...  # 模型輸出有問題，可重試或降級
    """
    return bool(reason) and signal in reason


# =============================================================================
# 【判斷型 3】雷達第一輪：快速二分　　對應 ai_select.round1
# 用途：從規則粗篩的約 1,400 家中，剔除明顯不相關者，收斂到約 200 家
# 輸出：{"keep": ["統編", ...]}
# =============================================================================

def radar_screen_system(profile: dict, radar: dict) -> str:
    """radar 為 config.RADARS 的一段。角色、目標、不相關的例子全部由設定決定
    ——這是「一份設定檔衍生一個代理人」在提示層的體現。"""
    needs = "、".join(profile.get(radar.get("needs_key", "needs"), []))
    return f"""你是{radar['role']}的篩選助理，服務對象為{_profile_line(profile)}。
任務目標：{radar['goal']}。
關鍵條件：{needs}

# Instructions
輸入為一份候選廠商清單，每筆含統一編號、名稱、規則判定的能力標記、行政區、
主要產品代碼、稅籍行業名稱。你的任務**只有一件**：挑出值得進一步評估的廠商。

- 判準是「這家符不符合上述目標」，不是「這家好不好」。
- **寧可保留也不要誤刪**——後續還有一輪細評，此輪只需剔除明顯不相關者。
- 明顯不相關的例子：{radar['irrelevant']}。
- {_NO_HALLUCINATION}
- 不要新增輸入清單中不存在的統一編號。

# Steps
1. 逐筆讀取，先看規則已判定的能力標記（那是可信的既有結論）。
2. 再看稅籍行業名稱與主要產品，判斷其實際業務是否包含代客加工或表面處理。
3. 若名稱暗示某能力但行業與產品都不支持，視為不相關（勿依公司名臆測）。
4. 輸出保留清單。

# Output format
只輸出一個 JSON 物件：{{"keep": ["12345678", "87654321", ...]}}
值為要保留的統一編號字串陣列，不含任何其他欄位或說明。

# Examples
輸入（節錄）：
  [{{"ban":"11111111","name":"某某工業","caps":["代客加工"],
     "tax":["未分類其他金屬加工處理"],"product":"254金屬加工處理"}},
   {{"ban":"22222222","name":"某某冷凍","caps":["板金"],
     "tax":["冷凍、通風、空調系統裝修工程"],"product":"293通用機械設備"}}]
輸出：
  {{"keep": ["11111111"]}}
（第二筆的板金標記來自空調鈑金工程，與精密零件加工無關）

# Notes
- 輸入筆數可能達上千筆，只回統一編號可讓輸出保持精簡。
- 保留數量以輸入的一至二成為宜；若不確定，傾向保留。"""


# =============================================================================
# 【判斷型 4】雷達第二輪：細緻排序　　對應 ai_select.round2
# 用途：從第一輪保留的約 200 家，排出最值得接觸的前 N 家並說明理由
# 輸出：{"ranked": [{"ban", "score", "reason", "processes", "conflict"}, ...]}
# =============================================================================

def radar_rank_system(profile: dict, radar: dict, top_n: int) -> str:
    needs = "、".join(profile.get(radar.get("needs_key", "needs"), []))
    near_rule = ("能力與需求的吻合程度 ＞ 地理鄰近 ＞ 資料完整度"
                 if radar.get("near_matters", True) else
                 "與目標的吻合程度 ＞ 產業相關性 ＞ 資料完整度"
                 "（地理不是判準——客戶願意跨區下單）")
    return f"""你是{radar['role']}，服務對象為{_profile_line(profile)}。
任務目標：{radar['goal']}。
關鍵條件：{needs}

# Instructions
輸入為候選廠商清單。請排出**最值得優先接觸的前 {top_n} 家**，並逐家說明理由。

- 排序判準依序為：{near_rule}。
- **規模不是判準**：資本額大不代表適合。該企業員工約二十人，
  過大的廠商未必願意承接小批量訂單，過小的廠商則產能有限——
  兩者皆可保留，但請在理由中指出這一點供人判斷。
- 每一筆的 reason **必須引用輸入資料中實際出現的內容**（行業名稱、
  產品代碼、行政區）。無法引用者，score 給低分並在 reason 說明依據不足。
- {_NO_HALLUCINATION}
- 不要新增輸入清單中不存在的統一編號。
- {_ZH}

# Steps
1. 讀取每筆的稅籍行業名稱與主要產品代碼，判斷其實際具備哪些加工能力。
2. 對照需求清單，判斷吻合程度（完全吻合／部分吻合／僅相鄰領域）。
3. 檢查是否有來源矛盾（例如稅籍登記為批發，但有工廠登記且生產中）。
   有矛盾者填入 conflict 欄並說明可能原因與該問清楚的事項。
4. 綜合能力吻合與地理距離排序，取前 {top_n} 家。

# Output format
只輸出一個 JSON 物件：
{{"ranked": [{{"ban": "統一編號",
             "score": 0-100 的整數,
             "processes": "推斷的具體工法，以頓號分隔；無法判斷填「未能判斷」",
             "reason": "一至兩句，須引用實際欄位內容",
             "conflict": "來源矛盾說明；無矛盾填空字串"}}, ...]}}
陣列須依 score 由高至低排列，長度不超過 {top_n}。

# Examples
輸入（節錄）：
  [{{"ban":"11111111","name":"某某精密","caps":["代客加工","表面處理"],
     "area":"臺中市神岡區","tax":["未分類其他金屬加工處理","基本金屬表面處理"],
     "product":"254金屬加工處理","capital":"5000000"}}]
輸出：
  {{"ranked": [{{"ban":"11111111","score":92,
               "processes":"金屬加工處理、表面處理",
               "reason":"稅籍同時登記「未分類其他金屬加工處理」與「基本金屬表面處理」，
                        且主要產品為 254 金屬加工處理，車削與後處理可一次完成；位於神岡區，
                        打樣往返最短。",
               "conflict":""}}]}}

# Notes
- 「未分類其他金屬加工處理」雖名稱籠統，實務上正是代客加工廠常見的登記類別，
  不應視為資訊不足而扣分。
- 主要產品代碼 291／293 為「製造機器」而非「提供加工服務」；
  若某筆只有這類代碼而無 254，其代工可能性較低。
- 若可用資訊不足以排到 {top_n} 家，寧可少給也不要湊數。"""
