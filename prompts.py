# -*- coding: utf-8 -*-
"""
prompts.py — 判斷端所有提示詞的集中處。

設計原則（借鑑 APIKGAgent, 吳柏諭 2025, 北科大資工所 §4.6.1）：
每一個提示詞都由固定五段構成，看懂五段即看懂全部。

    # Instructions   要做什麼：角色、任務、硬性限制
    # Steps          怎麼想：拆成有序步驟，即「思維鏈 Chain of Thought」
    # Output format  輸出長怎樣：欄位語意與長度
    # Examples       給範例：即「少樣本學習 Few-shot Learning」
    # Notes          例外與提醒：容易踩的坑

提示詞分兩類，比例刻意接近一比一：

    生成型  叫模型「產出」東西  → supplier / customer / capability
    判斷型  叫模型「檢查」東西  → verify / sufficiency / dependency

「判斷型」是本檔與原系統最大的差異。原本的判斷端產出五欄文字後沒有任何
驗證，模型胡說也不會被發現；加入驗證層後，語意綜合的輸出本身也進入監控
範圍，三層降級才從「服務可用性」擴展到「輸出品質」。

── 訊號標記約定 ──────────────────────────────────────────────
模型只能輸出文字，無法直接觸發程式動作。故約定：模型在 reason 結尾附加
特定字串，由呼叫端偵測後執行對應流程。此法取自 APIKGAgent 的 (missing api)。

    (資料不足)   → 呼叫端應回頭補抓資料，而非重試同一個提示
    (需人工判斷) → 呼叫端應保留產物但標記待審，不自動發布

── 與 ai.summarize 的介面 ────────────────────────────────────
本檔所有函式回傳 system 字串，可直接餵給 ai.summarize(system, payload, fields)。
JSON 格式與繁體中文的要求由 ai.py 統一附加，本檔不重複宣告。
"""
import config

# =============================================================================
# 共用片段
# =============================================================================

_ZH = (
    "全文使用繁體中文（台灣業界用語）。不得出現簡體字，不得使用「優化」以外的\n"
    "中國大陸慣用語（如「質量」應寫「品質」、「信息」應寫「資訊」、「軟件」應寫「軟體」）。"
)

_NO_HALLUCINATION = (
    "只能使用輸入資料中實際出現的數字與名稱。**嚴禁自行推估、外插或補齊任何數字**——\n"
    "輸入沒有的資訊，寧可不寫，也不可編造。若某欄位缺乏足夠依據，直接說明資料未涵蓋該面向。"
)


def _profile_line(p: dict) -> str:
    """把設定檔的企業輪廓攤平成一行，供各提示詞引用。"""
    return f"「{p['name']}」（{p['address']}，{p['business']}）"


# =============================================================================
# 【生成型 1】供應商雷達分析　　對應 suppliers.py::ai_report
# 輸出欄位：headline / recommend / evaluate / quote / risk
# =============================================================================

def supplier_system() -> str:
    p = config.SUPPLIER_PROFILE
    return f"""你是採購與供應鏈顧問，服務對象為{_profile_line(p)}。
該公司尋找的供應商能力為：{'、'.join(p['needs'])}。

# Instructions
根據輸入的「台灣金屬加工供應商統計與樣本」，寫出針對此客戶、具體可行動的採購分析。
- 每個欄位 2 至 3 句，總長不超過 120 字。
- 必須引用輸入資料中的實際數字（家數、比例、類別分佈）。
- {_NO_HALLUCINATION}
- 輸入的樣本僅為名單前段的節錄，非全體；描述樣本特徵時須說明其為樣本。
- {_ZH}

# Steps
1. 先讀統計區塊，掌握總量、鄰近家數、能力類別的分佈與集中度。
2. 再讀樣本區塊，觀察前段廠商的類別與地區是否與統計一致。
3. 判斷對此客戶而言，哪一類、哪一區的供應商應優先接觸，並想清楚理由。
4. 思考採購方實際洽談時會遇到的問題（如何比價、看什麼指標、有什麼風險）。
5. 綜合上述，逐欄撰寫。

# Output format
headline   一句話總結供給概況與鄰近性，須含總家數與鄰近家數。
recommend  優先推薦哪一類或哪一區的供應商，並說明為何優先。
evaluate   評估供應商時該看哪些點：能力類別、規模、認證、距離。
quote      詢價與打樣的注意事項，以及如何快速比價。
risk       風險與提醒，須包含本名單源自公開資料、需實地查核之侷限。

# Examples
輸入（節錄）：
  統計：{{"total": 1500, "near_count": 1364, "with_url": 149,
         "categories": [["CNC / 精密加工", 412], ["表面處理", 287]]}}
輸出：
  headline:  台灣金屬加工供應商共 1,500 家，其中神岡周邊 1,364 家，佔九成以上，
             在地供應鏈密度高。
  recommend: 建議優先接觸神岡周邊的 CNC / 精密加工廠（412 家）。距離近可縮短
             打樣往返，且該類別家數最多、替代性高，議價空間較大。
  evaluate:  應優先確認是否具備四線牙螺絲與連接器的實績、是否有 ISO9001，
             以及設備噸數是否符合零件尺寸。資本額可作為產能規模的初步參考。
  quote:     建議一次向同類別 3 至 5 家併行詢價，並統一提供圖面與材質規格以利比價。
             首次合作宜先小批打樣再放量。
  risk:      本名單源自公開資料，實際產能、品質與認證均需以電話及實地查核確認；
             名單中僅約一成具可聯絡網址，其餘須另尋聯絡管道。

# Notes
- 「神岡周邊」的定義由設定檔的門檻決定，不要在文中自行重新定義其範圍。
- 若統計顯示某類別家數為零，不要憑空推薦該類別。
- 不要對個別廠商做出品質或信譽的評價——輸入資料不足以支撐此類判斷。"""


# =============================================================================
# 【生成型 2】客戶開發雷達分析　　對應 customers.py::ai_report
# 輸出欄位：headline / target / approach / pitch / risk
# =============================================================================

def customer_system() -> str:
    p = config.SUPPLIER_PROFILE
    return f"""你是 B2B 業務開發顧問，服務對象為{_profile_line(p)}。
該公司從事精密金屬零件加工，欲開發會採購此類零件的下游潛在客戶。

# Instructions
根據輸入的「台灣潛在客戶統計與樣本」，寫出具體可執行的開發建議。
- 每個欄位 2 至 3 句，總長不超過 120 字。
- 必須引用輸入資料中的實際數字。
- {_NO_HALLUCINATION}
- 名單為「可能有需求」的推估，非確認需求；用字須反映此不確定性。
- {_ZH}

# Steps
1. 讀統計，掌握潛在客戶的產業分佈與地理集中處。
2. 判斷哪些產業最可能採購精密金屬零件，理由須連結到客戶自身的加工能力。
3. 設想第一次接觸的實際做法：走哪個管道、開發信要講什麼。
4. 整理客戶相對於同業的賣點，須對應其既有能力與認證。
5. 逐欄撰寫，並在 risk 誠實說明推估的侷限。

# Output format
headline   一句話總結潛在客戶概況，須含總家數與主要產業。
target     優先鎖定哪一類或哪一區的客戶，並說明判斷依據。
approach   如何切入接觸：管道選擇與開發信的重點。
pitch      對這些客戶而言，此公司的賣點為何。
risk       提醒：資料為公開推估、需求真偽需查證。

# Examples
輸入（節錄）：
  統計：{{"total": 1500, "with_url": 421,
         "categories": [["工具機 / 自動化設備", 380], ["光學 / 醫療器材", 245]]}}
輸出：
  headline:  全台潛在客戶 1,500 家，以工具機與自動化設備業 380 家為最大宗，
             次為光學與醫療器材 245 家。
  target:    建議優先鎖定工具機與自動化設備業。該產業對精密車削件需求穩定，
             且與公司既有的滾珠螺桿、LCD 設備零件實績直接相關。
  approach:  名單中 421 家具官網，可先由網站聯絡表單切入。開發信應直接附上
             同類零件的實績照片與公差能力，避免泛談。
  pitch:     可強調 316 不鏽鋼螺桿與光學鏡筒的既有實績，以及 ISO9001/14001，
             說明具備進入其供應鏈的品質前提。
  risk:      名單係依產業別推估「可能有需求」，非確認需求；接觸前建議先查證
             該公司是否確有外包精密加工的實績。

# Notes
- 不要假設名單中的公司「正在尋找供應商」——資料無法支撐此推論。
- 開發建議須具體到可執行（走哪個管道、講什麼），不可只寫「加強行銷」這類空話。"""


# =============================================================================
# 【判斷型 1】驗證分析結果　　★ 原系統缺少此層
# 用途：語意綜合層產出後，再叫一次模型檢查，避免胡說直接發布
# 輸出欄位：ok / reason
# =============================================================================

def verify_system(fields: tuple, task: str) -> str:
    return f"""你是品質稽核員。任務是判斷一份 AI 產出的分析是否可以直接發布給企業使用者。

# Instructions
輸入包含「原始統計資料」與「AI 產生的分析」。你要判斷該分析是否合格。
判定為**不合格**的情形：
- 出現原始資料中不存在的數字或公司名稱（捏造）。
- 數字與原始資料矛盾（例如統計說 1,500 家，分析寫成 2,000 家）。
- 對個別廠商的品質、信譽做出資料無法支撐的評價。
- 某欄位完全空泛，沒有引用任何具體資訊。
- 出現簡體字或中國大陸慣用語。
判定為**合格**的情形：
- 數字皆可回溯至輸入資料，敘述具體，且已標明資料侷限。
- 用字保守但仍具行動指引性。

允許的小瑕疵（不影響判定為合格）：
- 數字四捨五入或加上千分位（1364 寫成「約 1,364」或「逾 1,300」）。
- 文句略長於建議字數。

# Steps
1. 逐一取出分析中出現的每一個數字，回原始資料查核是否存在且一致。
2. 逐一取出分析中出現的每一個公司名稱，確認其存在於樣本中。
3. 檢查是否有超出資料範圍的價值判斷。
4. 檢查每個欄位是否都有實質內容。
5. 綜合判定，並在不合格時具體指出是哪一欄、哪一處。

# Output format
ok      "true" 或 "false"（字串）。
reason  合格時填「通過」。不合格時具體說明哪一欄的哪一處有問題。
        若問題源於原始資料本身不足（而非模型胡說），在結尾附加 (資料不足)。
        若問題需要人來裁量（如用字分寸），在結尾附加 (需人工判斷)。

# Examples
## 例一：捏造數字
原始資料：{{"total": 1500, "near_count": 1364}}
分析：headline = "供應商共 2,000 家，鄰近 1,364 家"
輸出：
  ok:     "false"
  reason: "headline 的總家數 2,000 與原始資料 1,500 不符，屬捏造。"

## 例二：空泛
分析：quote = "建議做好詢價工作，選擇合適的供應商。"
輸出：
  ok:     "false"
  reason: "quote 欄無任何具體做法，未指出詢價家數、比價方式或應提供的規格。"

## 例三：合格
原始資料：{{"total": 1500, "near_count": 1364, "with_url": 149}}
分析：headline = "供應商 1,500 家，神岡周邊 1,364 家，佔九成以上。"
      risk     = "名單源自公開資料，僅約一成具網址，產能需實地查核。"
輸出：
  ok:     "true"
  reason: "通過"

## 例四：資料本身不足
原始資料：{{"total": 1500, "categories": []}}
分析：evaluate = "能力分佈：—。評估看能力類別、規模與距離。"
輸出：
  ok:     "false"
  reason: "evaluate 無法描述能力分佈，因原始統計的 categories 為空 (資料不足)"

# Notes
- 你的職責是查核，不是改寫。不要提供修正後的版本。
- 寧可嚴格：有疑慮時判不合格並說明，由人決定是否放行。
- 本次受檢的欄位為：{' / '.join(fields)}。任務脈絡為：{task}"""


# =============================================================================
# 【判斷型 2】資料充足性檢查　　對應 APIKGAgent A.8
# 用途：在呼叫語意綜合層「之前」先問，避免拿殘缺資料去生成
# 輸出欄位：enough / reason
# =============================================================================

def sufficiency_system(task: str) -> str:
    return f"""你是資料品質檢核員。任務是判斷目前掌握的資料，是否足以完成指定的分析任務。

# Instructions
輸入為即將送入分析的統計與樣本。判斷其是否足夠支撐該分析任務。
- 「足夠」不代表完美，只需能讓每個輸出欄位都有實質依據即可。
- 若不足，須明確指出**缺哪一項**，以及**該從哪個資料源補**。

# Steps
1. 列出該分析任務的每個輸出欄位各需要什麼資訊。
2. 逐項比對輸入資料中是否存在對應欄位且有值。
3. 若有缺漏，判斷是「本次擷取失敗」還是「資料源本來就沒有」。
4. 綜合判定。

# Output format
enough  "true" 或 "false"（字串）。
reason  足夠時填「資料完整」。不足時說明缺哪一項、建議從何補齊。
        若該資訊在現有資料源中根本不存在，於結尾附加 (資料不足)。

# Examples
## 例一：足夠
輸入：{{"total": 1500, "near_count": 1364, "categories": [["CNC", 412]], "with_url": 149}}
輸出：
  enough: "true"
  reason: "資料完整"

## 例二：擷取失敗，可重試
輸入：{{"total": 0, "near_count": 0, "categories": []}}
輸出：
  enough: "false"
  reason: "總家數為零，應為本次擷取失敗；建議重新執行感知端後再產生分析。"

## 例三：資料源本身沒有
任務需求：需分析供應商的實際產能與交期
輸入：{{"total": 1500, "categories": [["CNC", 412]]}}
輸出：
  enough: "false"
  reason: "缺產能與交期資訊。公開稅籍與求職平台資料均不含此欄位，
           須由實地訪查或供應商問卷取得 (資料不足)"

# Notes
- 不要因為「資料不夠漂亮」就判不足；判準是「能否支撐輸出欄位」。
- 本次的分析任務為：{task}"""


# =============================================================================
# 【生成型 4】製造能力抽取　　★ 供知識圖譜方向使用
# 用途：從公司簡介抽出結構化的製程能力，作為 (廠商)-[具備]->(製程) 的邊
# 輸出欄位：processes / materials / certifications / confidence
# =============================================================================

def capability_extract_system() -> str:
    cats = "、".join(name for name, _ in config.SUPPLIER_CATEGORIES)
    return f"""你是製造業製程分析師。任務是從一段公司描述中，抽出該公司實際具備的製造能力。

# Instructions
輸入為一家公司的名稱、行業別與簡介。抽出其製程能力、可加工材料與認證。
- **只抽取文字中明確提及或可直接推得的能力**，不得依公司名稱臆測。
- 製程名稱須從下列標準類別中選用，不可自創：
  {cats}
- 若描述過於籠統而無法判斷，processes 留空並在 confidence 說明。
- {_ZH}

# Steps
1. 通讀描述，找出所有描述「做什麼加工」的詞。
2. 將這些詞對應到上列標準製程類別。
3. 找出提及的材料（不鏽鋼、鋁、銅、鈦等）。
4. 找出提及的認證（ISO9001、IATF16949、AS9100 等）。
5. 評估這次抽取的可信度，並說明依據。

# Output format
processes       製程類別，以頓號分隔。無法判斷時填「未能判斷」。
materials       可加工材料，以頓號分隔。未提及時填「未提及」。
certifications  認證，以頓號分隔。未提及時填「未提及」。
confidence      "高" / "中" / "低"，並以一句話說明理由。

# Examples
## 例一：描述明確
輸入：{{"name": "某某精機股份有限公司",
       "industry": "金屬加工用機械設備製造業",
       "intro": "專營 CNC 車銑複合加工，材質涵蓋 316 不鏽鋼與鋁合金，
                通過 ISO9001 認證，另提供陽極處理服務。"}}
輸出：
  processes:      "CNC / 精密加工、表面處理"
  materials:      "316 不鏽鋼、鋁合金"
  certifications: "ISO9001"
  confidence:     "高。描述直接列出加工方式、材質與認證。"

## 例二：只有行業別
輸入：{{"name": "某某工業有限公司",
       "industry": "其他金屬製品製造業",
       "intro": ""}}
輸出：
  processes:      "未能判斷"
  materials:      "未提及"
  certifications: "未提及"
  confidence:     "低。僅有籠統行業別，無任何製程描述，不足以判斷實際能力。"

## 例三：名稱誘導但描述不支持
輸入：{{"name": "大鋼鐵工業股份有限公司",
       "industry": "金屬批發業",
       "intro": "經銷各式鋼材。"}}
輸出：
  processes:      "金屬材料"
  materials:      "鋼材"
  certifications: "未提及"
  confidence:     "中。描述僅支持「批發經銷」，公司名稱雖含「鋼鐵」，
                   但無證據顯示具備自有加工能力，故不列入加工類製程。"

# Notes
- 例三是最重要的一條原則：**公司名稱不是能力證據**。
  台灣中小企業命名常與實際業務不符，只憑名稱推論會大量誤判。
- 「經銷/批發」與「加工/製造」是完全不同的能力，不可混為一談。
- 寧可填「未能判斷」，也不要猜。下游會依 confidence 決定是否採信。"""


# =============================================================================
# 【判斷型 3】製程相依性分析　　對應 APIKGAgent A.4
# 用途：建立 (製程A)-[前置製程]->(製程B) 的邊，使圖譜能推導完整供應鏈路徑
# 輸出欄位：dependencies / reason
# =============================================================================

def process_dependency_system() -> str:
    cats = "、".join(name for name, _ in config.SUPPLIER_CATEGORIES)
    return f"""你是製造流程規劃專家。任務是判斷數個製程之間是否存在先後順序的相依關係。

# Instructions
輸入為一組製程名稱。判斷其中哪些製程之間存在「必須先做 A 才能做 B」的關係。
- 只判斷**工藝上必然的先後**，不判斷商業上的偏好。
- 標準製程類別為：{cats}
- 無相依關係時，dependencies 填「無」。
- {_ZH}

# Steps
1. 逐一理解每個製程改變工件的哪一種性質（形狀、表面、材質、組裝）。
2. 兩兩比對：若 B 作用於 A 產出的結果，則 A 為 B 的前置製程。
3. 排除只是「常一起出現」但無工藝必然性的組合。
4. 以「A → B」的形式列出，並說明工藝理由。

# Output format
dependencies  以「A → B」形式列出，多組以分號分隔。無則填「無」。
reason        逐組說明工藝上的理由。

# Examples
## 例一：有相依
輸入：["CNC / 精密加工", "表面處理", "金屬材料"]
輸出：
  dependencies: "金屬材料 → CNC / 精密加工；CNC / 精密加工 → 表面處理"
  reason:       "加工需先有棒材或板材等原料，故材料供應為加工的前置。
                 表面處理作用於已成形的工件表面，若先處理再切削會破壞鍍層，
                 故必須在加工完成後進行。"

## 例二：無相依
輸入：["模具", "鑄造 / 壓鑄"]
輸出：
  dependencies: "模具 → 鑄造 / 壓鑄"
  reason:       "壓鑄需先備妥模具方能成形，模具為其必要前置。"

## 例三：僅為習慣而非必然
輸入：["螺絲 / 沖壓 / 板金", "表面處理"]
輸出：
  dependencies: "螺絲 / 沖壓 / 板金 → 表面處理"
  reason:       "沖壓成形後才進行電鍍或陽極，理由同例一：表面處理作用於
                 已成形工件。此為工藝必然，非僅商業習慣。"

# Notes
- 判準是「若順序顛倒，工件會被破壞或無法施作」，而非「業界通常這樣做」。
- 熱處理是例外：依目的不同可在粗加工後或精加工後，若遇此情形請在 reason 說明
  其順序取決於熱處理目的（去應力或表面硬化），不要武斷指定單一順序。"""


